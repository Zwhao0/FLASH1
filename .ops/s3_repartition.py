#!/usr/bin/env python3
"""Repartition a legacy Megatron FP16 PP checkpoint without dropping optimizer state.

This utility is deliberately limited to same-topology PP layer reassignment:
standard (non-distributed) checkpoints, TP=1, DP=1, one model chunk, FP16,
same PP degree, and checkpoints written with Greyhound's explicit parameter
name metadata. It preserves tied input/output embeddings on their existing
stages and moves every transformer-layer model tensor, FP32 master parameter,
and optimizer state by global layer identity.

Example (inside the training image):
  PYTHONPATH=/workspace/Greyhound/Megatron-LM python .ops/s3_repartition.py \
      --source /ckpt/s3-metadata-smoke \
      --output /ckpt/s3-repartitioned \
      --source-split 4,4,4,4 --target-split 6,2,2,6

The output root must not already exist. The source is never modified.
"""

import argparse
import copy
import hashlib
import json
import os
import re
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Mapping, Sequence, Tuple

import torch


_LAYER_NAME = re.compile(r"^(?P<prefix>.*?layers)\.(?P<index>\d+)\.(?P<suffix>.+)$")
_LAYER_STATE_KEY = re.compile(r"^layers\.(?P<index>\d+)\.(?P<suffix>.+)$")
_OPT_GROUP_KEYS = ("wd_mult", "lr_mult", "is_expert_parallel")


def _parse_split(value: str, name: str) -> List[int]:
    try:
        split = [int(part.strip()) for part in value.split(",")]
    except ValueError as exc:
        raise ValueError("{} must be comma-separated positive integers".format(name)) from exc
    if not split or any(count <= 0 for count in split):
        raise ValueError("{} must contain only positive layer counts".format(name))
    return split


def _offsets(split: Sequence[int]) -> List[int]:
    result = []
    offset = 0
    for count in split:
        result.append(offset)
        offset += count
    return result


def _iteration_dir(source: Path) -> Path:
    source = source.expanduser().resolve()
    if source.is_dir() and re.fullmatch(r"iter_\d{7}", source.name):
        return source
    tracker = source / "latest_checkpointed_iteration.txt"
    if not tracker.is_file():
        raise FileNotFoundError(
            "source must be an iteration directory or a checkpoint root with latest_checkpointed_iteration.txt: {}".format(source)
        )
    marker = tracker.read_text().strip()
    if not marker.isdigit():
        raise ValueError("only numeric latest-checkpoint trackers are supported: {}".format(marker))
    directory = source / "iter_{:07d}".format(int(marker))
    if not directory.is_dir():
        raise FileNotFoundError("tracker selects missing iteration directory {}".format(directory))
    return directory


def _torch_load(path: Path) -> Dict[str, Any]:
    # These files are generated by the experiment itself and contain an
    # argparse.Namespace in `args`, which older PyTorch versions always load.
    try:
        return torch.load(str(path), map_location="cpu", weights_only=False)
    except TypeError:  # PyTorch versions before the weights_only argument.
        return torch.load(str(path), map_location="cpu")


def _checkpoint_path(iteration_dir: Path, pp_rank: int) -> Path:
    return iteration_dir / "mp_rank_00_{:03d}".format(pp_rank) / "model_optim_rng.pt"


def _load_shards(iteration_dir: Path, pp_size: int) -> List[Dict[str, Any]]:
    shards = []
    for rank in range(pp_size):
        path = _checkpoint_path(iteration_dir, rank)
        if not path.is_file():
            raise FileNotFoundError("missing PP shard {}".format(path))
        shard = _torch_load(path)
        if not isinstance(shard, dict):
            raise TypeError("checkpoint root is not a dict: {}".format(path))
        shards.append(shard)
    return shards


def _args_value(args: Any, key: str, default: Any = None) -> Any:
    if isinstance(args, Mapping):
        return args.get(key, default)
    return getattr(args, key, default)


def _validate_topology(shards: Sequence[Mapping[str, Any]], source_split: Sequence[int], target_split: Sequence[int]) -> int:
    pp_size = len(source_split)
    if pp_size != len(target_split):
        raise ValueError("source and target PP degrees must match")
    total_layers = sum(source_split)
    if sum(target_split) != total_layers:
        raise ValueError("source and target splits must cover the same total layer count")
    if total_layers < pp_size:
        raise ValueError("each PP stage must retain at least one transformer layer")

    iterations = set()
    for rank, shard in enumerate(shards):
        iteration = shard.get("iteration")
        iterations.add(iteration)
        args = shard.get("args")
        if args is None:
            raise ValueError("PP rank {} checkpoint has no args".format(rank))
        num_layers = int(_args_value(args, "num_layers", -1))
        tp_size = int(_args_value(args, "tensor_model_parallel_size", -1))
        checkpoint_pp = int(_args_value(args, "pipeline_model_parallel_size", -1))
        world_size = int(_args_value(args, "world_size", pp_size))
        virtual_pp = _args_value(args, "virtual_pipeline_model_parallel_size")
        expert_size = int(_args_value(args, "expert_model_parallel_size", 1))
        if num_layers != total_layers:
            raise ValueError("checkpoint num_layers={} but split covers {}".format(num_layers, total_layers))
        if tp_size != 1 or checkpoint_pp != pp_size or world_size != pp_size:
            raise ValueError("only TP=1, DP=1, unchanged PP checkpoints are supported")
        if virtual_pp not in (None, 1):
            raise ValueError("virtual pipeline parallelism is unsupported")
        if expert_size != 1:
            raise ValueError("expert parallelism is unsupported")
        if not bool(_args_value(args, "fp16", False)) or bool(_args_value(args, "bf16", False)):
            raise ValueError("only FP16 checkpoints are supported")
        if bool(_args_value(args, "use_dist_ckpt", False)):
            raise ValueError("distributed checkpoints are unsupported")
        if bool(_args_value(args, "use_distributed_optimizer", False)):
            raise ValueError("distributed optimizer checkpoints are unsupported")
        if bool(_args_value(args, "no_save_optim", False)):
            raise ValueError("optimizer state is absent by configuration")
        if "model" not in shard or "model0" in shard:
            raise ValueError("exactly one model chunk is required")
        if "optimizer" not in shard:
            raise ValueError("checkpoint has no optimizer state")
        if "greyhound_model_param_order" not in shard or "greyhound_param_names" not in shard:
            raise ValueError(
                "checkpoint lacks GREYHOUND_REPARTITION_METADATA=1 parameter names; refusing to infer optimizer identity"
            )
    if len(iterations) != 1 or None in iterations:
        raise ValueError("all PP shards must contain the same non-null iteration")
    return total_layers


def _layer_identity(name: str, pp_rank: int, source_offsets: Sequence[int], source_split: Sequence[int]) -> str:
    match = _LAYER_NAME.match(name)
    if not match:
        return "stage:{}:{}".format(pp_rank, name)
    local_index = int(match.group("index"))
    if local_index >= source_split[pp_rank]:
        raise ValueError("parameter {} has local layer {} outside PP rank {}".format(name, local_index, pp_rank))
    global_index = source_offsets[pp_rank] + local_index
    return "layer:{}:{}:{}".format(match.group("prefix"), global_index, match.group("suffix"))


def _param_name_parts(name: str) -> Tuple[str, int, str]:
    match = _LAYER_NAME.match(name)
    if not match:
        raise ValueError("expected transformer-layer parameter name, got {}".format(name))
    return match.group("prefix"), int(match.group("index")), match.group("suffix")


def _state_path_value(model_state: Mapping[str, Any], param_name: str, pp_rank: int, pp_size: int) -> Any:
    """Resolve a named parameter to its serialized model tensor.

    Megatron's final PP stage serializes the tied output embedding under the
    compatibility key `word_embeddings_for_head`, while named_parameters()
    reports `word_embeddings.weight`. This one explicit alias is known from
    GPTModel.state_dict_for_save_checkpoint; all other names must match exactly.
    """
    # Transformer ModuleList keys are flattened by the legacy checkpoint
    # serializer (`layers.0.weight` is a literal encoder key, rather than a
    # nested encoder['layers']['0']['weight'] object).
    layer_match = _LAYER_NAME.match(param_name)
    if layer_match and layer_match.group("prefix") == "language_model.encoder.layers":
        serialized_key = "layers.{}.{}".format(layer_match.group("index"), layer_match.group("suffix"))
        try:
            return model_state["language_model"]["encoder"][serialized_key]
        except (KeyError, TypeError):
            pass

    # ParallelTransformer inherits nn.Module.state_dict(), which serializes
    # its final norm as a flat encoder key such as `final_norm.weight`.
    if param_name.startswith("language_model.encoder."):
        serialized_key = param_name[len("language_model.encoder."):]
        try:
            return model_state["language_model"]["encoder"][serialized_key]
        except (KeyError, TypeError):
            pass

    parts = param_name.split(".")
    current: Any = model_state
    try:
        for part in parts:
            current = current[part]
        return current
    except (KeyError, TypeError):
        if pp_rank == pp_size - 1 and param_name == "word_embeddings.weight":
            return model_state["word_embeddings_for_head"]["weight"]
        raise ValueError("model state has no tensor for metadata parameter {!r} on PP rank {}".format(param_name, pp_rank))


def _layer_model_state(shard: Mapping[str, Any], pp_rank: int, source_offset: int, layer_count: int) -> Dict[int, Dict[str, Any]]:
    try:
        encoder = shard["model"]["language_model"]["encoder"]
    except (KeyError, TypeError) as exc:
        raise ValueError("expected legacy GPT model.language_model.encoder checkpoint structure") from exc
    result: Dict[int, Dict[str, Any]] = {}
    for key, value in encoder.items():
        match = _LAYER_STATE_KEY.match(key)
        if not match:
            continue
        local_index = int(match.group("index"))
        if local_index >= layer_count:
            raise ValueError("serialized key {} is outside PP rank {} split".format(key, pp_rank))
        global_index = source_offset + local_index
        suffix = match.group("suffix")
        if suffix in result.setdefault(global_index, {}):
            raise ValueError("duplicate serialized tensor for global layer {} key {}".format(global_index, suffix))
        result[global_index][suffix] = value
    if set(result) != set(range(source_offset, source_offset + layer_count)):
        raise ValueError("PP rank {} has missing serialized transformer layers: {}".format(pp_rank, sorted(result)))
    return result


def _optimizer_signature(group: Mapping[str, Any]) -> Tuple[Any, ...]:
    missing = [key for key in _OPT_GROUP_KEYS if key not in group]
    if missing:
        raise ValueError("optimizer group lacks stable bucket metadata: {}".format(missing))
    return tuple(group[key] for key in _OPT_GROUP_KEYS)


def _hash_value(value: Any) -> str:
    digest = hashlib.sha256()

    def add(item: Any) -> None:
        if torch.is_tensor(item):
            tensor = item.detach().cpu().contiguous()
            digest.update(b"TENSOR\0")
            digest.update(str(tensor.dtype).encode())
            digest.update(json.dumps(list(tensor.shape)).encode())
            digest.update(tensor.reshape(-1).view(torch.uint8).numpy().tobytes())
        elif isinstance(item, Mapping):
            digest.update(b"MAP\0")
            for key in sorted(item, key=lambda value: (type(value).__name__, repr(value))):
                add(key)
                add(item[key])
        elif isinstance(item, (list, tuple)):
            digest.update(b"TUPLE\0" if isinstance(item, tuple) else b"LIST\0")
            digest.update(str(len(item)).encode())
            for child in item:
                add(child)
        elif isinstance(item, bytes):
            digest.update(b"BYTES\0" + item)
        elif item is None:
            digest.update(b"NONE\0")
        elif isinstance(item, (str, int, float, bool)):
            digest.update((type(item).__name__ + "\0" + repr(item)).encode())
        else:
            digest.update((type(item).__qualname__ + "\0" + repr(item)).encode())

    add(value)
    return digest.hexdigest()


def _inventory_hash(inventory: Mapping[str, str]) -> str:
    digest = hashlib.sha256()
    for identity in sorted(inventory):
        digest.update(identity.encode("utf-8"))
        digest.update(b"\0")
        digest.update(inventory[identity].encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()


def _check_same_inventory(label: str, expected: Mapping[str, str], actual: Mapping[str, str]) -> None:
    if expected == actual:
        return
    missing = sorted(set(expected) - set(actual))[:8]
    added = sorted(set(actual) - set(expected))[:8]
    changed = sorted(key for key in set(expected) & set(actual) if expected[key] != actual[key])[:8]
    raise ValueError("{} identity audit failed (missing={}, added={}, changed={})".format(label, missing, added, changed))


def _extract_optimizer(shard: Mapping[str, Any], pp_rank: int, pp_size: int,
                       source_offsets: Sequence[int], source_split: Sequence[int]) -> Tuple[Dict[str, Dict[str, Any]], Dict[Tuple[Any, ...], Dict[str, Any]]]:
    wrapper = shard["optimizer"]
    if not isinstance(wrapper, Mapping) or not isinstance(wrapper.get("optimizer"), Mapping):
        raise ValueError("expected Float16OptimizerWithFloat16Params checkpoint state")
    if "fp32_from_fp16_params" not in wrapper or "grad_scaler" not in wrapper:
        raise ValueError("FP16 master parameters and grad scaler must be present")
    optimizer_state = wrapper["optimizer"]
    groups = optimizer_state.get("param_groups")
    states = optimizer_state.get("state")
    names_by_group = shard["greyhound_param_names"]
    masters_by_group = wrapper["fp32_from_fp16_params"]
    if not isinstance(groups, list) or not isinstance(states, Mapping):
        raise ValueError("unsupported optimizer state dictionary")
    if not (len(groups) == len(names_by_group) == len(masters_by_group)):
        raise ValueError("optimizer parameter groups, metadata names, and FP32 masters have different lengths")

    state_id_lookup = {int(key): key for key in states}
    params: Dict[str, Dict[str, Any]] = {}
    group_configs: Dict[Tuple[Any, ...], Dict[str, Any]] = {}
    seen_ids = set()
    model_names = shard["greyhound_model_param_order"]
    if len(set(model_names)) != len(model_names):
        raise ValueError("duplicate parameter name in greyhound_model_param_order")
    flattened_names = []

    for group_index, (group, names, masters) in enumerate(zip(groups, names_by_group, masters_by_group)):
        ids = group.get("params")
        if not isinstance(ids, list) or len(ids) != len(names) or len(ids) != len(masters):
            raise ValueError("optimizer group {} ID/name/master counts disagree".format(group_index))
        signature = _optimizer_signature(group)
        if signature in group_configs:
            raise ValueError("duplicate optimizer bucket signature {}".format(signature))
        config = {key: copy.deepcopy(value) for key, value in group.items() if key != "params"}
        group_configs[signature] = config
        for param_id, name, master in zip(ids, names, masters):
            if not torch.is_tensor(master) or master.dtype != torch.float32:
                raise ValueError("FP32 master missing for parameter {}".format(name))
            if int(param_id) in seen_ids:
                raise ValueError("duplicate optimizer parameter ID {}".format(param_id))
            seen_ids.add(int(param_id))
            if int(param_id) not in state_id_lookup:
                raise ValueError("optimizer state missing for parameter ID {}".format(param_id))
            identity = _layer_identity(name, pp_rank, source_offsets, source_split)
            if identity in params:
                raise ValueError("duplicate global optimizer identity {}".format(identity))
            params[identity] = {
                "name": name,
                "signature": signature,
                "master": master,
                "state": states[state_id_lookup[int(param_id)]],
            }
            flattened_names.append(name)

    if seen_ids != set(state_id_lookup):
        raise ValueError("optimizer has state IDs not represented in greyhound_param_names")
    if set(flattened_names) != set(model_names):
        raise ValueError("optimizer names do not cover greyhound_model_param_order exactly")
    for name in model_names:
        model_value = _state_path_value(shard["model"], name, pp_rank, pp_size)
        param = params[_layer_identity(name, pp_rank, source_offsets, source_split)]
        if not torch.is_tensor(model_value) or tuple(model_value.shape) != tuple(param["master"].shape):
            raise ValueError("model/FP32-master shape mismatch for {}".format(name))
    return params, group_configs


def _collect_model_layers(shards: Sequence[Mapping[str, Any]], source_split: Sequence[int]) -> Dict[int, Dict[str, Any]]:
    offsets = _offsets(source_split)
    result: Dict[int, Dict[str, Any]] = {}
    for rank, (shard, offset, count) in enumerate(zip(shards, offsets, source_split)):
        for global_index, values in _layer_model_state(shard, rank, offset, count).items():
            if global_index in result:
                raise ValueError("model layer {} appears in multiple source shards".format(global_index))
            result[global_index] = values
    if set(result) != set(range(sum(source_split))):
        raise ValueError("model layer inventory does not cover every global layer")
    suffixes = [set(result[index]) for index in range(sum(source_split))]
    if any(keys != suffixes[0] for keys in suffixes[1:]):
        raise ValueError("transformer layers have different serialized key sets")
    return result


def _build_model_inventory(shards: Sequence[Mapping[str, Any]], split: Sequence[int]) -> Dict[str, str]:
    offsets = _offsets(split)
    inventory: Dict[str, str] = {}
    for rank, shard in enumerate(shards):
        encoder = shard["model"]["language_model"]["encoder"]
        for key, value in encoder.items():
            match = _LAYER_STATE_KEY.match(key)
            if match:
                local_index = int(match.group("index"))
                if local_index >= split[rank]:
                    raise ValueError("serialized model layer outside declared PP split")
                global_index = offsets[rank] + local_index
                identity = "model.layer.{}.{}".format(global_index, match.group("suffix"))
            else:
                identity = "model.rank.{}.encoder.{}".format(rank, key)
            if identity in inventory:
                raise ValueError("duplicate model identity {}".format(identity))
            inventory[identity] = _hash_value(value)

        # Hash all serialized model leaves outside the encoder, including the
        # input embedding and the tied-output compatibility copy.
        for container_name, container in shard["model"].items():
            if container_name == "language_model":
                for sub_name, subvalue in container.items():
                    if sub_name == "encoder":
                        continue
                    identity = "model.rank.{}.language_model.{}".format(rank, sub_name)
                    inventory[identity] = _hash_value(subvalue)
            else:
                inventory["model.rank.{}.{}".format(rank, container_name)] = _hash_value(container)
    return inventory


def _build_optimizer_inventory(shards: Sequence[Mapping[str, Any]], split: Sequence[int]) -> Dict[str, str]:
    offsets = _offsets(split)
    inventory: Dict[str, str] = {}
    for rank, shard in enumerate(shards):
        params, group_configs = _extract_optimizer(shard, rank, len(split), offsets, split)
        for identity, entry in params.items():
            master_key = "optimizer.master.{}".format(identity)
            state_key = "optimizer.state.{}".format(identity)
            inventory[master_key] = _hash_value(entry["master"])
            inventory[state_key] = _hash_value(entry["state"])
        for signature, config in group_configs.items():
            key = "optimizer.group.{}".format(repr(signature))
            config_inventory = {k: v for k, v in config.items() if k not in ("step", "lr", "weight_decay")}
            # Those mutable schedule fields are also part of identity and must
            # match across ranks and the repartitioned checkpoint.
            config_inventory.update({k: config[k] for k in ("step", "lr", "weight_decay") if k in config})
            config_hash = _hash_value(config_inventory)
            if key in inventory and inventory[key] != config_hash:
                raise ValueError("optimizer group configuration differs between PP ranks")
            inventory[key] = config_hash
        inventory["optimizer.scaler.rank.{}".format(rank)] = _hash_value(shard["optimizer"]["grad_scaler"])
    return inventory


def _target_param_order(shards: Sequence[Mapping[str, Any]], source_split: Sequence[int],
                        target_split: Sequence[int], target_rank: int) -> List[str]:
    source_order = list(shards[target_rank]["greyhound_model_param_order"])
    parsed = []
    for name in source_order:
        match = _LAYER_NAME.match(name)
        parsed.append((name, match))
    layer_positions = [i for i, (_, match) in enumerate(parsed) if match]
    if not layer_positions:
        raise ValueError("parameter metadata contains no transformer layer names")
    first, last = min(layer_positions), max(layer_positions)
    if any(match is None for _, match in parsed[first:last + 1]):
        raise ValueError("non-layer model parameters are interleaved with transformer layer parameters")
    prefix_names = [name for name, match in parsed[:first] if match is None]
    suffix_names = [name for name, match in parsed[last + 1:] if match is None]

    template = None
    for rank, shard in enumerate(shards):
        layer_zero = []
        seen_local_layers = set()
        for name in shard["greyhound_model_param_order"]:
            match = _LAYER_NAME.match(name)
            if not match:
                continue
            index = int(match.group("index"))
            seen_local_layers.add(index)
            if index == 0:
                layer_zero.append((match.group("prefix"), match.group("suffix")))
        if seen_local_layers != set(range(source_split[rank])):
            raise ValueError("PP rank {} metadata does not cover its declared layer count".format(rank))
        if template is None:
            template = layer_zero
        elif layer_zero != template:
            raise ValueError("layer parameter name/order differs across source PP ranks")
    if not template:
        raise ValueError("cannot derive transformer parameter template")

    layer_names = []
    for local_index in range(target_split[target_rank]):
        layer_names.extend("{}.{}.{}".format(prefix, local_index, suffix) for prefix, suffix in template)
    return prefix_names + layer_names + suffix_names


def _repartition(shards: Sequence[Mapping[str, Any]], source_split: Sequence[int],
                 target_split: Sequence[int]) -> List[Dict[str, Any]]:
    pp_size = len(source_split)
    source_offsets = _offsets(source_split)
    target_offsets = _offsets(target_split)
    model_layers = _collect_model_layers(shards, source_split)

    optimizer_params: Dict[str, Dict[str, Any]] = {}
    group_configs_by_signature: Dict[Tuple[Any, ...], Dict[str, Any]] = {}
    for rank, shard in enumerate(shards):
        params, group_configs = _extract_optimizer(shard, rank, pp_size, source_offsets, source_split)
        for identity, entry in params.items():
            if identity in optimizer_params:
                raise ValueError("duplicate global optimizer parameter identity {}".format(identity))
            optimizer_params[identity] = entry
        for signature, config in group_configs.items():
            prior = group_configs_by_signature.get(signature)
            if prior is not None and _hash_value(prior) != _hash_value(config):
                raise ValueError("optimizer bucket {} differs between source PP ranks".format(signature))
            group_configs_by_signature[signature] = config

    target_shards = []
    for target_rank, original in enumerate(shards):
        target = copy.deepcopy(original)
        encoder = target["model"]["language_model"]["encoder"]
        for key in list(encoder):
            if _LAYER_STATE_KEY.match(key):
                del encoder[key]
        start = target_offsets[target_rank]
        end = start + target_split[target_rank]
        for global_index in range(start, end):
            for suffix, value in model_layers[global_index].items():
                encoder["layers.{}.{}".format(global_index - start, suffix)] = value

        target_order = _target_param_order(shards, source_split, target_split, target_rank)
        if len(target_order) != len(set(target_order)):
            raise ValueError("target PP rank {} parameter order contains duplicates".format(target_rank))
        target_identities = [
            _layer_identity(name, target_rank, target_offsets, target_split)
            for name in target_order
        ]
        if len(target_identities) != len(set(target_identities)):
            raise ValueError("target PP rank {} maps multiple parameters to one global identity".format(target_rank))
        if any(identity not in optimizer_params for identity in target_identities):
            missing = [identity for identity in target_identities if identity not in optimizer_params][:8]
            raise ValueError("optimizer identity missing for target PP rank {}: {}".format(target_rank, missing))

        original_optimizer = target["optimizer"]
        original_base = original_optimizer["optimizer"]
        original_groups = original_base["param_groups"]
        signatures_in_order = [_optimizer_signature(group) for group in original_groups]
        if len(signatures_in_order) != len(set(signatures_in_order)):
            raise ValueError("target stage has duplicate optimizer group signatures")
        grouped_names: List[List[str]] = []
        grouped_identities: List[List[str]] = []
        for signature in signatures_in_order:
            names = []
            identities = []
            for name, identity in zip(target_order, target_identities):
                if optimizer_params[identity]["signature"] == signature:
                    names.append(name)
                    identities.append(identity)
            if not names:
                raise ValueError("target PP rank {} has empty optimizer group {}".format(target_rank, signature))
            grouped_names.append(names)
            grouped_identities.append(identities)

        # The generated groups must match Megatron's deterministic bucket
        # order, not merely have the same set of parameters.
        expected_group_signatures = set(signatures_in_order)
        actual_group_signatures = {optimizer_params[identity]["signature"] for identity in target_identities}
        if actual_group_signatures != expected_group_signatures:
            raise ValueError("target optimizer bucket set differs from source stage")

        new_base = copy.deepcopy(original_base)
        new_state: Dict[int, Any] = {}
        next_param_id = 0
        for group, names, identities in zip(new_base["param_groups"], grouped_names, grouped_identities):
            ids = list(range(next_param_id, next_param_id + len(names)))
            group["params"] = ids
            next_param_id += len(names)
            for param_id, identity in zip(ids, identities):
                new_state[param_id] = copy.deepcopy(optimizer_params[identity]["state"])
        new_base["state"] = new_state
        original_optimizer["optimizer"] = new_base
        original_optimizer["fp32_from_fp16_params"] = [
            [copy.deepcopy(optimizer_params[identity]["master"]) for identity in identities]
            for identities in grouped_identities
        ]
        target["greyhound_model_param_order"] = target_order
        target["greyhound_param_names"] = grouped_names
        target_shards.append(target)
    return target_shards


def _save_shards(shards: Sequence[Mapping[str, Any]], output_iteration_dir: Path) -> None:
    output_iteration_dir.mkdir(parents=True, exist_ok=False)
    for rank, shard in enumerate(shards):
        shard_dir = output_iteration_dir / "mp_rank_00_{:03d}".format(rank)
        shard_dir.mkdir()
        target = shard_dir / "model_optim_rng.pt"
        temporary = target.with_suffix(".pt.tmp")
        torch.save(dict(shard), str(temporary))
        os.replace(str(temporary), str(target))


def _write_tracker(output_root: Path, iteration: int) -> None:
    tracker = output_root / "latest_checkpointed_iteration.txt"
    temporary = output_root / ".latest_checkpointed_iteration.txt.tmp"
    temporary.write_text(str(iteration) + "\n")
    os.replace(str(temporary), str(tracker))


def repartition(source: Path, output: Path, source_split: Sequence[int],
                target_split: Sequence[int], dry_run: bool = False) -> Dict[str, Any]:
    source_iteration_dir = _iteration_dir(source)
    source_root = source_iteration_dir.parent.resolve()
    output = output.expanduser().resolve()
    if source_root == output or source_root in output.parents or output in source_root.parents:
        raise ValueError("source and output roots must be separate")
    if output.exists():
        raise FileExistsError("output root already exists; refusing to overwrite: {}".format(output))

    source_shards = _load_shards(source_iteration_dir, len(source_split))
    total_layers = _validate_topology(source_shards, source_split, target_split)
    original_model = _build_model_inventory(source_shards, source_split)
    original_optimizer = _build_optimizer_inventory(source_shards, source_split)
    target_shards = _repartition(source_shards, source_split, target_split)
    planned_model = _build_model_inventory(target_shards, target_split)
    planned_optimizer = _build_optimizer_inventory(target_shards, target_split)
    _check_same_inventory("model", original_model, planned_model)
    _check_same_inventory("optimizer", original_optimizer, planned_optimizer)

    iteration = int(source_shards[0]["iteration"])
    report = {
        "source_iteration_dir": str(source_iteration_dir),
        "output_root": str(output),
        "iteration": iteration,
        "source_split": list(source_split),
        "target_split": list(target_split),
        "total_layers": total_layers,
        "model_identity_count": len(original_model),
        "optimizer_identity_count": len(original_optimizer),
        "model_sha256": _inventory_hash(original_model),
        "optimizer_sha256": _inventory_hash(original_optimizer),
        "pre_save_identity_checks": "passed",
        "roundtrip_check": "not_run" if dry_run else "pending",
    }
    if dry_run:
        return report

    output.parent.mkdir(parents=True, exist_ok=True)
    temporary_root = Path(tempfile.mkdtemp(prefix=".{}-s3-".format(output.name), dir=str(output.parent)))
    try:
        temporary_iteration = temporary_root / source_iteration_dir.name
        _save_shards(target_shards, temporary_iteration)
        _write_tracker(temporary_root, iteration)

        # Reload exactly what will be published and repeat global identity
        # checks. This catches serialization loss, wrong IDs, and bad offsets.
        roundtrip = _load_shards(temporary_iteration, len(target_split))
        _check_same_inventory("roundtrip model", original_model, _build_model_inventory(roundtrip, target_split))
        _check_same_inventory("roundtrip optimizer", original_optimizer, _build_optimizer_inventory(roundtrip, target_split))
        report["roundtrip_check"] = "passed"
        report["roundtrip_model_sha256"] = _inventory_hash(_build_model_inventory(roundtrip, target_split))
        report["roundtrip_optimizer_sha256"] = _inventory_hash(_build_optimizer_inventory(roundtrip, target_split))

        # Publish the complete root (all shards + tracker) in one rename.
        os.replace(str(temporary_root), str(output))
    except Exception:
        shutil.rmtree(str(temporary_root), ignore_errors=True)
        raise
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path,
                        help="checkpoint root with tracker, or one iter_XXXXXXX directory")
    parser.add_argument("--output", required=True, type=Path,
                        help="new checkpoint root to create; existing output is rejected")
    parser.add_argument("--source-split", required=True,
                        help="source PP layer counts, e.g. 4,4,4,4")
    parser.add_argument("--target-split", required=True,
                        help="target PP layer counts, e.g. 6,2,2,6")
    parser.add_argument("--dry-run", action="store_true",
                        help="validate and print identity hashes without writing output")
    parser.add_argument("--audit-json", type=Path,
                        help="write the final audit report to this path")
    args = parser.parse_args()

    try:
        source_split = _parse_split(args.source_split, "--source-split")
        target_split = _parse_split(args.target_split, "--target-split")
        report = repartition(args.source, args.output, source_split, target_split, args.dry_run)
        output = json.dumps(report, indent=2, sort_keys=True)
        print(output)
        if args.audit_json:
            args.audit_json.parent.mkdir(parents=True, exist_ok=True)
            args.audit_json.write_text(output + "\n")
        return 0
    except Exception as exc:
        print("S3 repartition refused: {}".format(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
